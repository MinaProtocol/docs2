#!/usr/bin/env node
/**
 * Builds static/graphql-api/schema.graphql, the SDL form of
 * static/graphql-api/schema.json.
 *
 * schema.json is the introspection result that the Mina daemon serves,
 * copied from graphql_schema.json in the MinaProtocol/mina repository at the
 * release tag that .github/workflows/check-daemon-schema.yml pins. The daemon
 * is code-first (OCaml), so the introspection JSON is the source and the SDL
 * is derived from it, the reverse of the Archive Node API files.
 *
 *   node scripts/generate-daemon-schema-sdl.mjs
 */
import { readFile, writeFile } from 'node:fs/promises';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import {
  buildClientSchema,
  printSchema,
  lexicographicSortSchema,
} from 'graphql';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const JSON_PATH = join(ROOT, 'static', 'graphql-api', 'schema.json');
const SDL_PATH = join(ROOT, 'static', 'graphql-api', 'schema.graphql');

const introspection = JSON.parse(await readFile(JSON_PATH, 'utf8'));
const schema = lexicographicSortSchema(buildClientSchema(introspection));
const sdl = printSchema(schema);

const header = `# Mina daemon GraphQL API schema (SDL)
#
# Generated by scripts/generate-daemon-schema-sdl.mjs from schema.json in this
# folder, which is graphql_schema.json from the MinaProtocol/mina repository
# at a pinned release tag. Do not edit by hand; see
# .github/workflows/check-daemon-schema.yml for the pinned tag.
#
# Types are sorted alphabetically.

`;
await writeFile(SDL_PATH, header + sdl + '\n');

const counts = ['query', 'mutation', 'subscription'].map((name) => {
  const type = schema.getType(name);
  return `${name}: ${type ? Object.keys(type.getFields()).length : 0}`;
});
console.log(
  `Generated ${SDL_PATH} (${counts.join(', ')}, ${
    Object.keys(schema.getTypeMap()).filter((n) => !n.startsWith('__')).length
  } types)`
);
